@dataclass
class Line:
    kind: str
    text: str
    reg: int = -1
    rows: list[list[str]] | None = None   # table rows for kind == "table"


def article_lines(art: Article) -> list[tuple[str, str]]:
    """The exact logical lines of an article as they appear in the document."""
    if art.deleted:
        assert art.deleted_on is not None
        return [("article", f"{art.label} 삭제 <{fmt_date(art.deleted_on)}>")]
    out: list[tuple[str, str]] = []
    head = f"{art.label}({art.title})"
    numbered = len(art.paras) > 1
    for idx, para in enumerate(art.paras):
        text = (CIRCLED[idx] + " " if numbered else "") + para.text
        if idx == 0 and art.inline_first:
            out.append(("article", f"{head} {text}"))
        else:
            if idx == 0:
                out.append(("article", head))
            out.append(("para", text))
        for k, item in enumerate(para.items):
            out.append(("item", f"{k + 1}. {item.text}"))
            for j, sub in enumerate(item.subs):
                out.append(("sub", f"{GANADA[j]}. {sub}"))
    return out


def toc_entry_text(number: str, title: str, page: int, total_width: float = 400.0, size: float = 10.0) -> str:
    left = f"{number}. {title} "
    right = f" {page}"
    dots = max(6, int((total_width - text_width(left, size) - text_width(right, size)) / (char_em(".") * size)))
    return f"{left}{'.' * dots}{right}"


def regulation_lines(reg: Regulation) -> list[Line]:
    ri = reg.idx
    lines = [
        Line("reg_header", f"{reg.number}. {reg.title}", ri),
        Line("reg_title", reg.title, ri),
        Line("revision", f"제정 {fmt_date(reg.enact)}", ri),
        Line("revision", "개정 " + ", ".join(fmt_date(d) for d in reg.amendments), ri),
    ]
    current_chapter = -1
    current_section = -2
    for art in reg.articles:
        if art.chapter != current_chapter:
            current_chapter = art.chapter
            current_section = -2
            ch = reg.chapters[current_chapter]
            lines.append(Line("chapter", f"제{ch.no}장 {ch.title}", ri))
        if art.section != current_section:
            current_section = art.section
            if current_section >= 0:
                sec = reg.chapters[current_chapter].sections[current_section]
                lines.append(Line("section", f"제{current_section + 1}절 {sec}", ri))
        for kind, text in article_lines(art):
            lines.append(Line(kind, text, ri))
    for add in reg.addenda:
        lines.append(Line("addendum", f"부칙 <{fmt_date(add.date)}>", ri))
        for cl in add.clauses:
            lines.append(Line("article", f"제{cl.num}조({cl.title}) {cl.text}", ri))
    for appx in reg.appendices:
        lines.append(Line("appendix", f"[별표 {appx.no}] {appx.title}({appx.ref} 관련)", ri))
        lines.append(Line("table", "", ri, rows=[appx.header, *appx.rows]))
        if appx.note:
            lines.append(Line("note", appx.note, ri))
    for form in reg.forms:
        lines.append(Line("form", f"[별지 제{form.no}호서식] {form.title}", ri))
        lines.append(Line("table", "", ri, rows=[["구분", "작성 내용"], *form.rows]))
        for text in form.footer:
            lines.append(Line("note", text, ri))
    return lines


def front_matter_lines(book: Book, pages: dict[int, int], cover: bool = True) -> list[Line]:
    lines: list[Line] = []
    if cover:
        lines.append(Line("cover_title", BOOK_TITLE))
        lines.append(Line("cover_sub", f"({fmt_date_kr(SNAPSHOT)} 현재)"))
    lines.append(Line("toc_title", "목 차"))
    for reg in book.regs:
        lines.append(Line("toc_entry", toc_entry_text(reg.number, reg.title, pages.get(reg.idx, 0)), reg.idx))
    return lines


def book_lines(book: Book, pages: dict[int, int], cover: bool = True) -> list[Line]:
    out = front_matter_lines(book, pages, cover)
    for reg in book.regs:
        out.extend(regulation_lines(reg))
    return out


