_MARK = re.compile(r"<(?:개정|신설)[^<>]*>")


def article_text(art: Article) -> str:
    return "\n".join(text for _kind, text in article_lines(art))


def _article_record(reg: Regulation, art: Article) -> dict[str, Any]:
    text = article_text(art)
    return {
        "label": art.label,
        "number": art.num,
        "branch": art.branch or None,
        "title": art.title or None,
        "deleted": art.deleted,
        "deleted_on": iso_date(art.deleted_on) if art.deleted_on else None,
        "chapter": art.chapter + 1,
        "section": art.section + 1 if art.section >= 0 else None,
        "paragraph_count": len(art.paras),
        "item_count": sum(len(p.items) for p in art.paras),
        "anchor_key": art.key,
        "amendment_marks": _MARK.findall(text),
    }


def _pick_samples(reg: Regulation, rng: random.Random) -> list[Article]:
    live = [a for a in reg.articles if not a.deleted]
    picks: list[Article] = []

    def take(pool: list[Article]) -> None:
        pool = [a for a in pool if a not in picks]
        if pool and len(picks) < 3:
            picks.append(rng.choice(pool))

    take([a for a in live if a.key])
    take([a for a in live if a.branch])
    take([a for a in live if len(a.paras) >= 2 and any(p.items for p in a.paras)])
    while len(picks) < 3 and len(picks) < len(live):
        take(live)
    return sorted(picks, key=lambda a: reg.articles.index(a))


def _sample_record(reg: Regulation, art: Article) -> dict[str, Any]:
    lines = [text for _kind, text in article_lines(art)]
    text = "\n".join(lines)
    return {
        "label": art.label,
        "title": art.title,
        "heading": f"{art.label}({art.title})",
        "lines": lines,
        "text": text,
        "text_compact": compact(text),
        "char_count": len(text),
    }


def build_queries(book: Book, limit: int = 18) -> list[dict[str, Any]]:
    """Natural-language questions, each answered by exactly one article of the book."""
    rng = random.Random(stable_seed(book.seed, "queries"))
    compact_texts = [(r, a, compact(article_text(a))) for r in book.regs for a in r.articles if not a.deleted]
    by_reg: dict[int, list[tuple[Anchor, Article]]] = {}
    for _key, (ri, art, anc) in book.anchors.items():
        if anc.query:
            by_reg.setdefault(ri, []).append((anc, art))
    picks = [(ri, rng.choice(by_reg[ri])) for ri in sorted(by_reg)]
    if len(picks) > limit:
        picks = sorted(rng.sample(picks, limit), key=lambda p: p[0])
    out: list[dict[str, Any]] = []
    for n, (ri, (anc, art)) in enumerate(picks, start=1):
        reg = book.regs[ri]
        mine = compact(article_text(art))
        for must in anc.must:
            if compact(must) not in mine:
                raise AssertionError(f"query anchor {anc.reg}/{anc.key}: {must!r} missing from article text")
        needle = compact(max(anc.must, key=len))
        hits = [(r.title, a.label) for r, a, c in compact_texts if needle in c]
        if hits != [(reg.title, art.label)]:
            raise AssertionError(f"query anchor {anc.reg}/{anc.key} is not unique: {hits}")
        out.append({
            "id": f"Q{n:02d}",
            "query": anc.query,
            "expected": {
                "regulation": reg.title,
                "regulation_number": reg.number,
                "article": art.label,
                "article_title": art.title,
                "chapter": reg.chapters[art.chapter].title,
            },
            "must_contain": list(anc.must),
            "expected_text": article_text(art),
        })
    return out


def _ref_record(book: Book, ref: CrossRef) -> dict[str, Any]:
    src = book.regs[ref.source_reg]
    dst = book.regs[ref.target_reg]
    return {
        "kind": ref.kind,
        "source_regulation": src.title,
        "source_regulation_number": src.number,
        "source_article": ref.source_article,
        "source_paragraph": ref.source_para,
        "target_regulation": dst.title,
        "target_regulation_number": dst.number,
        "target_article": ref.target_article,
        "target_paragraph": ref.target_para,
        "text": ref.text,
    }


def build_ground_truth(book: Book, fmt: str, *, cover: bool, running_header: bool,
                       pdf_page_count: int, queries: list[dict[str, Any]]) -> dict[str, Any]:
    regs: list[dict[str, Any]] = []
    for reg in book.regs:
        rng = random.Random(stable_seed(book.seed, "samples", reg.title))
        arts = [_article_record(reg, a) for a in reg.articles]
        chapters = []
        for ci, ch in enumerate(reg.chapters):
            chapters.append({
                "number": ch.no,
                "title": ch.title,
                "sections": list(ch.sections),
                "article_count": sum(1 for a in reg.articles if a.chapter == ci),
            })
        regs.append({
            "order": reg.idx + 1,
            "number": reg.number,
            "title": reg.title,
            "kind": reg.spec.kind,
            "part": reg.part,
            "part_title": PART_TITLES[reg.part],
            "parent_regulation": book.regs[reg.parent].title if reg.parent is not None else None,
            "child_regulation": book.regs[reg.child].title if reg.child is not None else None,
            "enacted": iso_date(reg.enact),
            "amendments": [iso_date(d) for d in reg.amendments],
            "revision_lines": [f"제정 {fmt_date(reg.enact)}", "개정 " + ", ".join(fmt_date(d) for d in reg.amendments)],
            "toc_page": reg.start_page,
            "chapters": chapters,
            "article_count": len(arts),
            "live_article_count": sum(1 for a in arts if not a["deleted"]),
            "deleted_article_count": sum(1 for a in arts if a["deleted"]),
            "branch_article_count": sum(1 for a in arts if a["branch"]),
            "articles": arts,
            "counts": {"addenda": len(reg.addenda), "appendices": len(reg.appendices), "forms": len(reg.forms)},
            "addenda": [{"date": iso_date(a.date), "header": f"부칙 <{fmt_date(a.date)}>", "clause_count": len(a.clauses)}
                        for a in reg.addenda],
            "appendices": [{"number": x.no, "label": f"[별표 {x.no}]", "title": x.title, "related_article": x.ref,
                            "row_count": len(x.rows) + 1} for x in reg.appendices],
            "forms": [{"number": x.no, "label": f"[별지 제{x.no}호서식]", "title": x.title, "related_article": x.ref}
                      for x in reg.forms],
            "sample_articles": [_sample_record(reg, a) for a in _pick_samples(reg, rng)],
        })
    refs = [_ref_record(book, r) for r in book.refs]
    totals = {
        "regulations": len(book.regs),
        "chapters": sum(len(r["chapters"]) for r in regs),
        "sections": sum(len(c["sections"]) for r in regs for c in r["chapters"]),
        "articles": sum(r["article_count"] for r in regs),
        "live_articles": sum(r["live_article_count"] for r in regs),
        "deleted_articles": sum(r["deleted_article_count"] for r in regs),
        "branch_articles": sum(r["branch_article_count"] for r in regs),
        "addenda": sum(r["counts"]["addenda"] for r in regs),
        "appendices": sum(r["counts"]["appendices"] for r in regs),
        "forms": sum(r["counts"]["forms"] for r in regs),
        "cross_references": sum(1 for r in refs if r["kind"] == "external"),
        "internal_references": sum(1 for r in refs if r["kind"] == "internal"),
        "delegation_references": sum(1 for r in refs if r["kind"] == "delegation"),
        "queries": len(queries),
    }
    return {
        "schema": GROUND_TRUTH_SCHEMA,
        "generator_version": GENERATOR_VERSION,
        "seed": book.seed,
        "format": fmt,
        "source_file": f"{BOOK_STEM}.{fmt}",
        "institution": INSTITUTION,
        "book_title": BOOK_TITLE,
        "snapshot_date": iso_date(SNAPSHOT),
        "layout": {"cover_page": cover, "running_header_on_every_pdf_page": running_header,
                   "pdf_page_count": pdf_page_count,
                   "regulation_heading": "N-N-N. <title> on the first line of every regulation, then the plain title line"},
        "front_matter": {
            "cover_lines": [BOOK_TITLE, f"({fmt_date_kr(SNAPSHOT)} 현재)"] if cover else [],
            "contents_marker": "목 차",
            "contents_entry_count": len(book.regs),
            "contents_page_numbers": "physical PDF page numbers (the same text is used in docx and hwpx)",
        },
        "totals": totals,
        "regulations": regs,
        "cross_references": refs,
        "queries": queries,
        "notes": {
            "article_numbering": "every regulation restarts at 제1조; 제N조의M are branch articles; deleted articles read "
                                 "'제N조 삭제 <date>'",
            "sample_articles.lines": "exact logical lines of the article as written in the file (before PDF wrapping)",
            "article_count": "article entries in the regulation body (deleted placeholders and 조의N included); "
                             "the 제N조 clauses inside 부칙 are not counted",
            "cross_references.kind": "external = 「other regulation」 제N조; internal = 제N조 inside the same regulation; "
                                     "delegation = 시행세칙 link (target_article is null when only the regulation is named)",
        },
    }


