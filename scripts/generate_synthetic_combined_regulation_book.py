def dumps_json(data: Any) -> bytes:
    return (json.dumps(data, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def parse_formats(value: str) -> list[str]:
    formats = [f.strip().lower().lstrip(".") for f in value.split(",") if f.strip()]
    bad = [f for f in formats if f not in SUPPORTED_FORMATS]
    if bad or not formats:
        raise ValueError(f"--formats must be a comma list of {', '.join(SUPPORTED_FORMATS)} (got {value!r})")
    return list(dict.fromkeys(formats))


def generate(seed: int = DEFAULT_SEED, regulations: int = DEFAULT_REGULATIONS,
             formats: Sequence[str] = SUPPORTED_FORMATS, *, cover: bool = True,
             running_header: bool = False) -> tuple[Book, dict[str, tuple[bytes, bytes]]]:
    """Build the book and render it. Returns ``{format: (book bytes, ground-truth bytes)}``."""
    problems = validate_catalog()
    if problems:
        raise RuntimeError("inconsistent catalog: " + "; ".join(problems))
    book = build_book(seed, regulations)
    layout = paginate(book, running_header, cover)
    queries = build_queries(book)
    lines = book_lines(book, layout.start_pages, cover)
    outputs: dict[str, tuple[bytes, bytes]] = {}
    for fmt in formats:
        if fmt == "pdf":
            data = render_pdf(layout)
        elif fmt == "docx":
            data = render_docx(lines)
        elif fmt == "hwpx":
            data = render_hwpx(lines)
        else:  # pragma: no cover - parse_formats guards this
            raise ValueError(fmt)
        truth = build_ground_truth(book, fmt, cover=cover, running_header=running_header,
                                   pdf_page_count=len(layout.pages), queries=queries)
        outputs[fmt] = (data, dumps_json(truth))
    return book, outputs


def write_corpus(out_dir: Path, seed: int, regulations: int, formats: Sequence[str], *, cover: bool,
                 running_header: bool, command: str) -> dict[str, Any]:
    book, outputs = generate(seed, regulations, formats, cover=cover, running_header=running_header)
    files = []
    for fmt, (data, truth) in outputs.items():
        target = out_dir / fmt
        target.mkdir(parents=True, exist_ok=True)
        (target / f"{BOOK_STEM}.{fmt}").write_bytes(data)
        (target / f"{BOOK_STEM}.ground_truth.json").write_bytes(truth)
        files.append({
            "format": fmt,
            "path": f"{fmt}/{BOOK_STEM}.{fmt}",
            "bytes": len(data),
            "sha256": sha256_bytes(data),
            "ground_truth": f"{fmt}/{BOOK_STEM}.ground_truth.json",
            "ground_truth_sha256": sha256_bytes(truth),
        })
    first_truth = json.loads(next(iter(outputs.values()))[1])
    manifest = {
        "schema": "synthetic-combined-regulation-book-manifest-v1",
        "generator_version": GENERATOR_VERSION,
        "seed": seed,
        "regulations": regulations,
        "formats": list(outputs),
        "options": {"cover": cover, "running_header": running_header},
        "totals": first_truth["totals"],
        "pdf_page_count": first_truth["layout"]["pdf_page_count"],
        "files": files,
        "command": command,
    }
    (out_dir / "manifest.json").write_bytes(dumps_json(manifest))
    return manifest


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate a synthetic combined regulation book (총규정) plus ground-truth JSON.")
    parser.add_argument("--out-dir", type=Path, default=Path("synthetic_corpus"),
                        help="output directory (default: ./synthetic_corpus)")
    parser.add_argument("--regulations", type=int, default=DEFAULT_REGULATIONS,
                        help=f"number of regulations, 1..{MAX_REGULATIONS} (default {DEFAULT_REGULATIONS})")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help=f"random seed (default {DEFAULT_SEED})")
    parser.add_argument("--formats", default=",".join(SUPPORTED_FORMATS),
                        help="comma list of docx,pdf,hwpx (default: all three)")
    parser.add_argument("--no-cover", action="store_true",
                        help="omit the cover page (the book then starts with the contents)")
    parser.add_argument("--running-header", action="store_true",
                        help="repeat the 'N-N-N. title' heading at the top of every PDF page of a regulation "
                             "(stress variant that the structure detector is not expected to handle; "
                             "off by default)")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        formats = parse_formats(args.formats)
        if not 1 <= args.regulations <= MAX_REGULATIONS:
            raise ValueError(f"--regulations must be between 1 and {MAX_REGULATIONS}")
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    command = (f"python scripts/generate_synthetic_combined_regulation_book.py --out-dir <out-dir> "
               f"--regulations {args.regulations} --seed {args.seed} --formats {','.join(formats)}"
               + (" --no-cover" if args.no_cover else "") + (" --running-header" if args.running_header else ""))
    started = time.perf_counter()
    manifest = write_corpus(args.out_dir, args.seed, args.regulations, formats, cover=not args.no_cover,
                            running_header=args.running_header, command=command)
    totals = manifest["totals"]
    print(f"regulations={totals['regulations']} articles={totals['articles']} deleted={totals['deleted_articles']} "
          f"branch={totals['branch_articles']} addenda={totals['addenda']} appendices={totals['appendices']} "
          f"forms={totals['forms']} cross_refs={totals['cross_references']} queries={totals['queries']} "
          f"pdf_pages={manifest['pdf_page_count']}")
    for item in manifest["files"]:
        print(f"{args.out_dir / item['path']}  {item['bytes']:,} bytes")
    print(f"done in {time.perf_counter() - started:.1f}s")
    return 0


if __name__ == "__main__":
    sys.exit(main())
