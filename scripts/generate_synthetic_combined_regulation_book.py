def build_book(seed: int = DEFAULT_SEED, regulations: int = DEFAULT_REGULATIONS) -> Book:
    specs = select_specs(regulations)
    by_title = {s.title: i for i, s in enumerate(specs)}
    all_anchors = _anchors()
    group_ctr: dict[int, int] = {}
    group_of: dict[str, int] = {}
    seq_ctr: dict[tuple[int, int], int] = {}
    regs: list[Regulation] = []
    plans: list[list[Slot]] = []
    book = Book(seed, regs, [], by_title, {})

    # ---- phase A: structure and numbering --------------------------------------------------
    for i, spec in enumerate(specs):
        parent_idx = by_title.get(spec.parent) if spec.parent else None
        if parent_idx is not None and specs[parent_idx].part != spec.part:
            parent_idx = None
        if parent_idx is not None:
            grp = group_of[specs[parent_idx].title]
        else:
            group_ctr[spec.part] = group_ctr.get(spec.part, 0) + 1
            grp = group_ctr[spec.part]
        group_of[spec.title] = grp
        seq_ctr[(spec.part, grp)] = seq_ctr.get((spec.part, grp), 0) + 1
        number = f"{spec.part}-{grp}-{seq_ctr[(spec.part, grp)]}"
        size = max(14, round(spec.size * SIZE_SCALE))
        rng = random.Random(stable_seed(seed, "plan", spec.title))
        amend_count = max(4, min(14, 4 + size // 14 + rng.randint(-1, 4)))
        enact, amendments = make_dates(rng, amend_count)
        if len(amendments) != amend_count:
            raise RuntimeError(f"could not draw {amend_count} amendment dates for {spec.title}")
        reg = Regulation(i, spec, number, enact, amendments, parent=parent_idx)
        regs.append(reg)
    for reg in regs:
        if reg.parent is not None:
            regs[reg.parent].child = reg.idx
    for reg in regs:
        spec = reg.spec
        size = max(14, round(spec.size * SIZE_SCALE))
        rng = random.Random(stable_seed(seed, "slots", spec.title))
        anchors = [a for a in all_anchors if a.reg == spec.title]
        reg.chapters, slots = plan_regulation(spec, rng, size, anchors, reg.child is not None)
        assign_flags(slots, rng, size)
        reg.articles = number_articles(slots, rng, reg.amendments)
        plans.append(slots)
        for art, slot in zip(reg.articles, slots):
            if slot.anchor is not None:
                art.title = slot.anchor.title
                book.anchors[(spec.title, slot.anchor.key)] = (reg.idx, art, slot.anchor)
        reg.appendices = []
        for n, (title, kind) in enumerate(spec.appx, start=1):
            reg.appendices.append(Appendix(n, title, kind))
        for n, title in enumerate(spec.forms, start=1):
            reg.forms.append(Form(n, title))

    # ---- phase A.5: anchor paragraphs (their labels are final now) ----------------------------
    appendix_refs: dict[tuple[int, int], str] = {}
    for reg in regs:
        for art, slot in zip(reg.articles, plans[reg.idx]):
            if slot.anchor is not None:
                paras, refs = resolve_anchor(book, reg.idx, art, slot.anchor, appendix_refs)
                art.paras = paras
                book.refs.extend(refs)

    # ---- phase B: generated text, appendices, forms, addenda --------------------------------------
    for reg in regs:
        refs = generate_regulation(book, reg, plans[reg.idx], seed, appendix_refs)
        book.refs.extend(refs)
    for reg in regs:
        rng = random.Random(stable_seed(seed, "extras", reg.title))
        dom = DOMAINS[reg.spec.domain]
        for appx in reg.appendices:
            appx.header, appx.rows, appx.note = make_appendix_table(rng, appx.kind, dom)
        for form in reg.forms:
            form.rows, form.footer = make_form_rows(form.title, dom)
        reg.addenda = make_addenda(rng, reg)
    # anchors citing anchors recorded their source paragraph before later paragraphs were known
    for ref in book.refs:
        src = book.regs[ref.source_reg]
        art = next((a for a in src.articles if a.label == ref.source_article), None)
        if art is not None and len(art.paras) <= 1:
            ref.source_para = None
    book.refs.sort(key=lambda r: (r.source_reg, _article_sort_key(r.source_article), r.source_para or 0,
                                  r.kind, r.target_reg, r.target_article or ""))
    return book


def _article_sort_key(label: str) -> tuple[int, int]:
    m = re.fullmatch(r"제(\d+)조(?:의(\d+))?", label or "")
    if not m:
        return (0, 0)
    return (int(m.group(1)), int(m.group(2) or 0))


