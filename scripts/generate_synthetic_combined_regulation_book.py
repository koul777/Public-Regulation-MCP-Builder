SIZE_SCALE = 1.25
_TOKEN = re.compile(r"⟦(APPX|X):([^⟧]*)⟧")


def all_specs() -> list[Spec]:
    return _specs() + _extra_specs()


def validate_catalog() -> list[str]:
    """Return a list of catalog problems (empty when the catalog is consistent)."""
    problems: list[str] = []
    specs = all_specs()
    titles = [s.title for s in specs]
    if len(set(titles)) != len(titles):
        problems.append("duplicate regulation titles")
    if len({s.prio for s in specs}) != len(specs):
        problems.append("duplicate prio values")
    by_title = {s.title: s for s in specs}
    for s in specs:
        nouns = [n for _c, ns in s.chapters for n in ns]
        if len(set(nouns)) != len(nouns):
            problems.append(f"{s.title}: duplicate nouns")
        if s.parent and s.parent not in by_title:
            problems.append(f"{s.title}: unknown parent {s.parent}")
        if round(s.size * SIZE_SCALE) - 7 < len(nouns) + 2:
            problems.append(f"{s.title}: size {s.size} too small for {len(nouns)} nouns")
        if s.domain not in DOMAINS:
            problems.append(f"{s.title}: unknown domain {s.domain}")
    seen: set[tuple[str, str]] = set()
    for a in _anchors():
        spec = by_title.get(a.reg)
        if spec is None:
            problems.append(f"anchor for unknown regulation {a.reg}")
            continue
        if (a.reg, a.key) in seen:
            problems.append(f"duplicate anchor {a.reg}/{a.key}")
        seen.add((a.reg, a.key))
        if a.chapter not in [c for c, _ in spec.chapters]:
            problems.append(f"anchor {a.reg}/{a.key}: chapter {a.chapter!r} not in spec")
        for m in _TOKEN.finditer(a.body):
            if m.group(1) == "APPX" and int(m.group(2)) >= len(spec.appx):
                problems.append(f"anchor {a.reg}/{a.key}: appendix index {m.group(2)} missing")
            if m.group(1) == "X":
                target, key = m.group(2).split(":")
                if (target, key) not in {(x.reg, x.key) for x in _anchors()}:
                    problems.append(f"anchor {a.reg}/{a.key}: unknown target {target}/{key}")
        for must in a.must:
            if must not in a.body and must not in a.title:
                problems.append(f"anchor {a.reg}/{a.key}: must {must!r} not in body")
    keys = {(a.reg, a.key) for a in _anchors()}
    for src, dst, key, sentence in LINKS:
        if src not in by_title or dst not in by_title:
            problems.append(f"link {src}->{dst}: unknown regulation")
        if (dst, key) not in keys:
            problems.append(f"link {src}->{dst}/{key}: unknown anchor")
        if "{REF}" not in sentence:
            problems.append(f"link {src}->{dst}: sentence without {{REF}}")
    return problems


def select_specs(n: int) -> list[Spec]:
    specs = all_specs()
    if not 1 <= n <= len(specs):
        raise ValueError(f"--regulations must be between 1 and {len(specs)} (got {n})")
    chosen = sorted(specs, key=lambda s: s.prio)[:n]
    order = {s.title: i for i, s in enumerate(specs)}
    chosen.sort(key=lambda s: (s.part, order[s.title]))
    return chosen


def split_counts(total: int, weights: Sequence[int], minimums: Sequence[int]) -> list[int]:
    """Distribute ``total`` over buckets (largest remainder) honouring minimums."""
    rest = total - sum(minimums)
    if rest < 0:
        raise ValueError("total smaller than the sum of minimums")
    wsum = sum(weights) or 1
    raw = [rest * w / wsum for w in weights]
    add = [int(x) for x in raw]
    left = rest - sum(add)
    for i in sorted(range(len(raw)), key=lambda i: (-(raw[i] - add[i]), i))[:left]:
        add[i] += 1
    return [m + a for m, a in zip(minimums, add)]


def _section_title(nouns: Sequence[str]) -> str:
    return f"{nouns[0]} 및 {nouns[1]}" if len(nouns) >= 2 else nouns[0]


def plan_regulation(spec: Spec, rng: random.Random, size: int, anchors: Sequence[Anchor],
                    has_child: bool) -> tuple[list[Chapter], list[Slot]]:
    chapters = [Chapter(1, "총칙")]
    slots: list[Slot] = []
    general_kinds = ("purpose", "name", "seat", "relation") if spec.kind == "정관" \
        else ("purpose", "definition", "scope", "relation")
    for gk in general_kinds:
        slots.append(Slot(0, -1, gk, "general", general=gk))
    closing_kinds = ("child" if has_child else "delegate", "amend", "review")
    avail = size - len(general_kinds) - len(closing_kinds)
    mid = [(name, list(nouns)) for name, nouns in spec.chapters]
    while sum(len(n) for _c, n in mid) > avail:
        biggest = max(range(len(mid)), key=lambda k: len(mid[k][1]))
        mid[biggest][1].pop()
    mid = [(c, n) for c, n in mid if n]
    quotas = split_counts(avail, [len(n) for _c, n in mid], [len(n) for _c, n in mid])
    by_chapter: dict[str, list[Anchor]] = {}
    for a in anchors:
        by_chapter.setdefault(a.chapter, []).append(a)

    for ci, ((cname, nouns), quota) in enumerate(zip(mid, quotas), start=1):
        chapter = Chapter(ci + 1, cname)
        chapters.append(chapter)
        group_of = [-1] * len(nouns)
        if len(nouns) >= 5 and quota >= 12:
            g = 2 if len(nouns) < 8 else 3
            sizes = split_counts(len(nouns), [1] * g, [1] * g)
            pos = 0
            for gi, sz in enumerate(sizes):
                group = nouns[pos:pos + sz]
                chapter.sections.append(_section_title(group))
                for j in range(pos, pos + sz):
                    group_of[j] = gi
                pos += sz
        counts = [1] * len(nouns)
        extra = quota - len(nouns)
        guard = 0
        while extra > 0 and guard < 10_000:
            guard += 1
            j = rng.randrange(len(nouns))
            if counts[j] < len(POOL) + 1:
                counts[j] += 1
                extra -= 1
        cslots: list[Slot] = []
        for j, noun in enumerate(nouns):
            kinds = ["base"] + sorted(rng.sample(POOL, counts[j] - 1), key=POOL.index)
            for k in kinds:
                cslots.append(Slot(ci, group_of[j], noun, k))
        for anc in by_chapter.get(cname, []):
            best, best_score = None, -1.0
            for idx, s in enumerate(cslots):
                if s.anchor is not None:
                    continue
                score = rng.random() * 0.5 + (2.0 if s.arche == "base" else 0.0)
                if anc.topic and (anc.topic in s.noun or s.noun in anc.topic):
                    score += 4.0
                if score > best_score:
                    best, best_score = idx, score
            if best is not None:
                cslots[best].anchor = anc
        slots.extend(cslots)

    for kind in closing_kinds:
        slots.append(Slot(len(chapters), -1, kind, "closing", general=kind))
    chapters.append(Chapter(len(chapters) + 1, "보칙"))
    # the closing slots were created with the index of the (not yet appended) 보칙 chapter
    for s in slots:
        if s.arche == "closing":
            s.chapter = len(chapters) - 1
    return chapters, slots


def assign_flags(slots: list[Slot], rng: random.Random, size: int) -> None:
    def eligible(i: int) -> bool:
        s = slots[i]
        return (i > 0 and s.arche not in ("general", "closing") and s.anchor is None
                and slots[i - 1].chapter == s.chapter)

    for i in range(len(slots)):
        if not eligible(i):
            continue
        r = rng.random()
        if r < 0.05:
            slots[i].flag = "deleted"
        elif r < 0.12 and slots[i - 1].flag != "deleted":
            slots[i].flag = "branch"
    if size >= 25:
        if not any(s.flag == "deleted" for s in slots):
            cands = [i for i in range(len(slots)) if eligible(i) and slots[i].flag == "normal"
                     and (i + 1 >= len(slots) or slots[i + 1].flag != "branch")]
            if cands:
                slots[rng.choice(cands)].flag = "deleted"
        if not any(s.flag == "branch" for s in slots):
            cands = [i for i in range(len(slots)) if eligible(i) and slots[i].flag == "normal"
                     and slots[i - 1].flag != "deleted"]
            if cands:
                slots[rng.choice(cands)].flag = "branch"
    # a branch article must never follow a deleted one (checked once more after forcing)
    for i in range(1, len(slots)):
        if slots[i].flag == "branch" and slots[i - 1].flag == "deleted":
            slots[i].flag = "normal"


def number_articles(slots: list[Slot], rng: random.Random, amendments: Sequence[Date]) -> list[Article]:
    arts: list[Article] = []
    main = 0
    branch = 0
    for s in slots:
        if s.flag == "branch":
            branch += 1
            art = Article(main, branch + 1, s.chapter, s.section, arche=s.arche, noun=s.noun)
        else:
            main += 1
            branch = 0
            art = Article(main, 0, s.chapter, s.section, arche=s.arche, noun=s.noun)
            if s.flag == "deleted":
                art.deleted_on = rng.choice(list(amendments))
        if s.anchor is not None:
            art.key = s.anchor.key
        arts.append(art)
    return arts


