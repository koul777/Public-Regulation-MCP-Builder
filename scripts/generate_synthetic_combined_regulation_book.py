Date = tuple[int, int, int]


def fmt_date(d: Date) -> str:
    """``2015. 7. 1.`` (official short form without zero padding)."""
    return f"{d[0]}. {d[1]}. {d[2]}."


def fmt_date_kr(d: Date) -> str:
    return f"{d[0]}년 {d[1]}월 {d[2]}일"


def iso_date(d: Date) -> str:
    return f"{d[0]:04d}-{d[1]:02d}-{d[2]:02d}"


def _days_in_month(year: int, month: int) -> int:
    if month == 2:
        return 29 if (year % 4 == 0 and (year % 100 != 0 or year % 400 == 0)) else 28
    return 30 if month in (4, 6, 9, 11) else 31


def make_dates(rng: random.Random, amendment_count: int) -> tuple[Date, list[Date]]:
    """Return (enactment date, ascending amendment dates), all unique, <= SNAPSHOT."""
    enact_year = rng.randint(2004, 2016)
    enact = (enact_year, rng.randint(1, 12), rng.choice([1, 1, 1, 1, 15, 20]))
    seen = {enact}
    out: list[Date] = []
    span_days = (_dt.date(*SNAPSHOT) - _dt.date(*enact)).days
    attempts = 0
    while len(out) < amendment_count and attempts < 500:
        attempts += 1
        offset = rng.randint(120, max(121, span_days))
        base = _dt.date(*enact) + _dt.timedelta(days=offset)
        day = rng.choice([1, 1, 1, 1, 1, 15, 20, 25, 28, 30, 31])
        day = min(day, _days_in_month(base.year, base.month))
        cand = (base.year, base.month, day)
        if cand in seen or cand <= enact or cand > SNAPSHOT:
            continue
        seen.add(cand)
        out.append(cand)
    out.sort()
    return enact, out


