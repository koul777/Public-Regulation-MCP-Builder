def _table_widths(rows: Sequence[Sequence[str]], total: int) -> list[int]:
    ncol = len(rows[0])
    weights = [max(len(r[c]) for r in rows) + 4 for c in range(ncol)]
    widths = [max(900, total * w // sum(weights)) for w in weights]
    widths[-1] += total - sum(widths)
    return widths


def _docx_table(rows: Sequence[Sequence[str]]) -> str:
    widths = _table_widths(rows, 9400)
    border = ''.join(f'<w:{side} w:val="single" w:sz="4" w:space="0" w:color="000000"/>'
                     for side in ("top", "left", "bottom", "right", "insideH", "insideV"))
    out = [f'<w:tbl><w:tblPr><w:tblW w:w="{sum(widths)}" w:type="dxa"/><w:tblBorders>{border}</w:tblBorders>'
           '<w:tblLayout w:type="fixed"/></w:tblPr><w:tblGrid>']
    out.extend(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out.append('</w:tblGrid>')
    for row in rows:
        out.append('<w:tr>')
        for w, cell in zip(widths, row):
            out.append(f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/></w:tcPr>'
                       f'{_docx_paragraph("TableText", cell)}</w:tc>')
        out.append('</w:tr>')
    out.append('</w:tbl>')
    return "".join(out)


