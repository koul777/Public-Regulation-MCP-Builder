"""Generate a synthetic combined regulation book (총규정) plus machine-readable ground truth.

A "총규정" is a single file that concatenates many regulations of one public
institution.  This script fabricates one for a *fictional* institution
(한국공공가상연구원) so that the preprocessing pipeline (parse -> structure
detection -> chunking -> human approval -> index -> MCP) can be exercised on a
large, realistic, fully reproducible input without any real institution data.

What is generated (deterministic for a given ``--seed``)::

    <out-dir>/<format>/combined_book.<format>
    <out-dir>/<format>/combined_book.ground_truth.json
    <out-dir>/manifest.json

``<format>`` is any of ``pdf``, ``docx``, ``hwpx`` (``--formats``).  The three
formats carry the same logical text.  The ground truth lists, per regulation,
the title, chapters, every article number (with ``조의2`` branch articles and
deleted ``삭제`` placeholders flagged), 부칙 / 별표 / 별지 counts, three sample
articles with their exact source lines, every cross reference (internal and to
other regulations of the book) and a set of natural-language search queries that
are each answered by exactly one article.

The document follows how Korean public-institution regulation books look:
cover, ``목 차`` with dot leaders, ``제N편`` part dividers, numbered regulation
headings (``1-1-1. 인사규정``), ``제정``/``개정`` history lines, ``제N장``/``제N절``,
``제N조(제목)`` articles restarting at ``제1조`` in every regulation, ``①``/``1.``/``가.``
levels, ``제12조의2`` branch articles, ``제7조 삭제 <2020. 1. 1.>`` placeholders,
inline ``<개정 ...>`` marks, ``부칙`` blocks per amendment, ``[별표 N]`` tables and
``[별지 제N호서식]`` forms.

The fictional institution, all regulation text and every number in it are
invented.  No real person, institution identifier, path or secret is used.

Notes:

* The HWPX package is hand-built OWPML (one section per regulation).  It is
  only verified against this repository's ``HwpxParser``; it has not been
  opened in a word processor.  DOCX/HWPX parse as a single page, PDF as one
  page per physical page (the contents list uses physical page numbers).
* ``--running-header`` repeats the ``N-N-N. title`` heading on every PDF page of
  a regulation.  It is a deliberate stress variant (off by default) that the
  structure detector does not handle; the default layout is the one meant for
  end-to-end runs.
* ``--regulations`` above 48 appends extra regulations, up to 88.

Example::

    python scripts/generate_synthetic_combined_regulation_book.py \\
        --out-dir ./synthetic_corpus --regulations 48 --seed 20261010 \\
        --formats docx,pdf,hwpx
"""

