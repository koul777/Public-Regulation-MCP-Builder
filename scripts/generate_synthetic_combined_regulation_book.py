_STRUCT_START = re.compile(
    r"^(?:제\d+(?:조|항|호|장|절|편|관)|\d+[.)]|\(\d+\)|[①-⑳㉑-㉚]|[가-하][.)]|"
    r"별표|별지|부칙|붙임|목차|\[별|□)"
)
_DATE_TOKEN = re.compile(r"\d{4}\. \d{1,2}\. \d{1,2}\.,?")


def char_em(ch: str) -> float:
    """Advance width in em, slightly above the Droid Sans Fallback metric (never below it)."""
    o = ord(ch)
    if ch == " ":
        return 0.28
    if (0xAC00 <= o <= 0xD7A3 or 0x3131 <= o <= 0x318E or 0x2E80 <= o <= 0x9FFF
            or 0xFF00 <= o <= 0xFFEF or 0x3000 <= o <= 0x303F or 0x2460 <= o <= 0x24FF
            or 0x25A0 <= o <= 0x25FF):
        return 1.0
    if ch.isdigit():
        return 0.57
    if ch.isascii() and ch.isalpha():
        return 0.70 if ch.isupper() else 0.60
    if ch in ".,:;·":
        return 0.29
    if ch in "()[]":
        return 0.32
    if ch in "<>":
        return 0.57
    if ch == "-":
        return 0.34
    if ch in "“”‘’":
        return 0.38
    return 0.72


def text_width(text: str, size: float) -> float:
    return sum(char_em(c) for c in text) * size


def _tokens(text: str) -> list[str]:
    """Split on spaces but keep ``2019. 12. 30.`` dates in one unbreakable token."""
    masked = _DATE_TOKEN.sub(lambda m: m.group(0).replace(" ", "\u0001"), text)
    return [t.replace("\u0001", " ") for t in masked.split(" ") if t]


def wrap_text(text: str, width: float, size: float, first_indent: float = 0.0,
              hang: float = 0.0) -> list[str]:
    """Greedy word wrap.

    A wrapped continuation line never starts with something the structure
    detector would take for a heading (``제3조``, ``2.``, ``가.``, ``별표`` ...),
    so a re-flowed sentence cannot create a phantom article or item.
    """
    tokens = _tokens(text)
    if not tokens:
        return [""]
    lines: list[list[str]] = [[]]
    used = first_indent
    space = char_em(" ") * size
    for token in tokens:
        w = text_width(token, size)
        line = lines[-1]
        add = w if not line else w + space
        limit = width
        if line and used + add > limit:
            carry: list[str] = []
            if _STRUCT_START.match(token) and len(line) >= 2:
                carry = [line.pop()]
            new_line = carry + [token]
            lines.append(new_line)
            used = hang + sum(text_width(t, size) for t in new_line) + space * (len(new_line) - 1)
        else:
            line.append(token)
            used += add
        # hard-split a single over-long token
        while len(lines[-1]) == 1 and text_width(lines[-1][0], size) > width:
            long = lines[-1][0]
            cut = 1
            while cut < len(long) and text_width(long[: cut + 1], size) <= width - hang:
                cut += 1
            lines[-1] = [long[:cut]]
            lines.append([long[cut:]])
            used = hang + text_width(long[cut:], size)
    return [" ".join(parts) for parts in lines if parts]


def stable_seed(*parts: Any) -> str:
    return "|".join(str(p) for p in parts)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def compact(text: str) -> str:
    """Whitespace-free form used to compare article text across file formats."""
    return re.sub(r"\s+", "", text)


