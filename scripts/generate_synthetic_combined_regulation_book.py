def resolve_anchor(book: Book, reg_idx: int, art: Article, anc: Anchor,
                   appendix_refs: dict[tuple[int, int], str]) -> tuple[list[Para], list[CrossRef]]:
    """Turn an anchor body into paragraphs, resolving appendix and cross-reference tokens."""
    paras: list[Para] = []
    refs: list[CrossRef] = []

    def sub(text: str) -> str:
        def repl(m: re.Match[str]) -> str:
            if m.group(1) == "APPX":
                n = int(m.group(2))
                appendix_refs[(reg_idx, n)] = art.label
                return f"별표 {n + 1}"
            target, key = m.group(2).split(":")
            hit = book.anchors.get((target, key))
            if hit is None:
                return "관계 규정"
            t_idx, t_art, _anc = hit
            refs.append(CrossRef("external", reg_idx, art.label, len(paras) or 1, t_idx, t_art.label, None,
                                 f"「{target}」 {t_art.label}"))
            return f"「{target}」 {t_art.label}"
        return _TOKEN.sub(repl, text)

    for line in anc.body.split("\n"):
        if line.startswith("-- "):
            paras[-1].items[-1].subs.append(sub(line[3:]))
        elif line.startswith("- "):
            paras[-1].items.append(Item(sub(line[2:])))
        else:
            paras.append(Para(""))
            paras[-1].text = sub(line)
    return paras, refs


def _general_article(g: Gen, book: Book, reg: Regulation, kind: str) -> tuple[str, list[Para]]:
    spec = reg.spec
    if kind == "purpose":
        verb = "정함" if spec.kind in ("지침", "강령", "세칙") else "규정함"
        if spec.parent and reg.parent is not None:
            parent = book.regs[reg.parent]
            link = next((a for a in parent.articles if a.arche == "closing" and a.noun == "child"), None)
            if link is not None:
                g.refs.append(CrossRef("delegation", reg.idx, "제1조", None, parent.idx, link.label, None,
                                       f"「{parent.title}」 {link.label}"))
                return "목적", [P(g.f("이 {K:은} 「{PT}」 {L}에 따라 위임된 사항과 그 시행에 필요한 사항을 {V} 목적으로 한다.",
                                       PT=parent.title, L=link.label, V=f"{verb}을"))]
        purpose = spec.purpose
        if purpose.startswith("「"):
            purpose = f"{(spec.parent or spec.title).replace(' 시행세칙', '')}의 시행에 필요한 세부 사항"
        return "목적", [P(g.f("이 {K:은} {P:을} {V} 목적으로 한다.", P=purpose, V=f"{verb}을"))]
    if kind == "name":
        return "명칭", [P(f"{ORG}의 명칭은 “{INSTITUTION}”이라 한다.")]
    if kind == "seat":
        return "사무소", [P(f"{ORG}의 주된 사무소는 가상시에 두고, 필요한 경우 이사회의 의결을 거쳐 분사무소를 둘 수 있다.")]
    if kind == "definition":
        items = [Item(f"{josa(f'“{ORG}”', '이란')} {josa(INSTITUTION, '을')} 말한다.")]
        for term, desc in DEFS.get(spec.domain, ()):
            items.append(Item(f"{josa(f'“{term}”', '이란')} {josa(desc, '을')} 말한다."))
        return "정의", [P(g.f("이 {K}에서 사용하는 용어의 뜻은 다음과 같다."), items)]
    if kind == "scope":
        subject = SCOPE_SUBJECT.get(spec.domain, "부서와 임직원")
        return "적용 범위", [P(g.f("이 {K:은} {ORG}의 모든 {S}에게 적용한다. 다만, 다른 법령이나 규정에 특별한 규정이 있는 경우에는 그에 따른다.",
                                  ORG=ORG, S=subject))]
    if kind == "relation":
        paras = [P(g.f("이 {K}에서 정하지 아니한 사항은 관계 법령과 {ORG}의 다른 규정에서 정하는 바에 따른다.", ORG=ORG))]
        for src, dst, key, sentence in LINKS:
            if src != spec.title:
                continue
            hit = book.anchors.get((dst, key))
            if hit is None:
                continue
            t_idx, t_art, t_anc = hit
            para = None
            if len(t_art.paras) >= 2 and g.rng.random() < 0.35:
                para = 1
            ref_text = f"「{dst}」 {_para_label(t_art, para)}"
            paras.append(P(sentence.replace("{REF}", ref_text)))
            g.refs.append(CrossRef("external", reg.idx, "", len(paras), t_idx, t_art.label, para, ref_text))
        # the source article label is filled in by the caller (the number is known there)
        return "다른 규정과의 관계", paras
    if kind == "child":
        child = book.regs[reg.child]  # type: ignore[index]
        text = f"「{child.title}」"
        g.refs.append(CrossRef("delegation", reg.idx, "", 1, child.idx, None, None, text))
        return "시행세칙", [P(g.f("이 {K}의 시행에 필요한 세부 사항은 {CH:로} 정한다.", CH=text))]
    if kind == "delegate":
        return "세부 사항의 위임", [P(g.f("이 {K}의 시행에 필요한 세부 사항은 {H:이} 따로 정한다."))]
    if kind == "amend":
        return "개정 절차", [P(g.f("이 {K:을} 개정하려는 경우에는 {D}의 검토를 거쳐 {H}의 결재를 받아야 한다. 다만, 이사회의 의결을 거쳐야 하는 사항은 그에 따른다."))]
    if kind == "review":
        return "재검토 기한", [P(g.f("{H:은} 이 {K}에 대하여 2026년 1월 1일을 기준으로 매 3년이 되는 시점마다 그 타당성을 검토하여 개선 등의 조치를 하여야 한다."))]
    raise ValueError(kind)


def _apply_marks(art: Article, rng: random.Random, amendments: Sequence[Date]) -> None:
    if art.deleted or not art.paras:
        return
    if art.branch:
        mark = f"<신설 {fmt_date(rng.choice(list(amendments)))}>"
    elif rng.random() < 0.22:
        picks = sorted(rng.sample(list(amendments), min(len(amendments), rng.choice((1, 1, 2)))))
        mark = "<개정 " + ", ".join(fmt_date(d) for d in picks) + ">"
    else:
        return
    para = art.paras[rng.randrange(len(art.paras))]
    para.text = f"{para.text} {mark}"


def generate_regulation(book: Book, reg: Regulation, slots: list[Slot], seed: int,
                        appendix_refs: dict[tuple[int, int], str]) -> list[CrossRef]:
    rng = random.Random(stable_seed(seed, "text", reg.title))
    spec = reg.spec
    g = Gen(rng, spec, {r.title: r.idx for r in book.regs})
    seen_titles: set[str] = set()
    for art, slot in zip(reg.articles, slots):
        g.cur_chapter = art.chapter
        if art.deleted:
            art.title = ""
            art.paras = []
            continue
        if slot.anchor is not None:
            seen_titles.add(art.title)
            g.done.append(art)
            continue
        if slot.arche in ("general", "closing"):
            title, paras = _general_article(g, book, reg, slot.general)
            # fill the source article label of the references recorded just now
            for ref in g.refs:
                if ref.source_reg == reg.idx and not ref.source_article:
                    ref.source_article = art.label
        else:
            g.pending_ref = None
            title, paras = ARCHETYPES[slot.arche](g, slot.noun)
            if g.pending_ref is not None:
                label, para, text = g.pending_ref
                g.refs.append(CrossRef("internal", reg.idx, art.label, 1, reg.idx, label, para, text))
                g.pending_ref = None
        if title in seen_titles:
            title = f"{title} 관련 사항"
        seen_titles.add(title)
        art.title = title
        art.paras = paras
        if slot.arche not in ("general", "closing") and rng.random() < 0.12:
            ref = g.internal_ref()
            if ref is not None:
                text, label, para = ref
                template = rng.choice(EXTRA_REF_TEMPLATES)
                art.paras.append(P(g.f(template, REF=text, N=slot.noun)))
                g.refs.append(CrossRef("internal", reg.idx, art.label, len(art.paras), reg.idx, label, para, text))
        g.done.append(art)

    # attach appendices and forms to articles that mention them
    eligible = [a for a in reg.articles if not a.deleted and a.key is None and a.arche not in ("general", "closing")]
    eligible = eligible or [a for a in reg.articles if not a.deleted]
    for appx in reg.appendices:
        ref = appendix_refs.get((reg.idx, appx.no - 1))
        if ref is None:
            pool = [a for a in eligible if a.arche == "std"] or eligible
            host = pool[rng.randrange(len(pool))]
            host.paras.append(P(kf("구체적인 내용은 별표 {no:과} 같다.", no=appx.no)))
            ref = host.label
        appx.ref = ref
    for form in reg.forms:
        pool = [a for a in eligible if a.arche == "proc"] or eligible
        host = pool[rng.randrange(len(pool))]
        host.paras.append(P(kf("{F:은} 별지 제{no}호서식에 따라 작성하여 제출한다.", F=form.title, no=form.no)))
        form.ref = host.label

    for art in reg.articles:
        _apply_marks(art, rng, reg.amendments)
        art.inline_first = len(art.paras) <= 1 or rng.random() < 0.3
    for ref in g.refs:
        art = next((a for a in reg.articles if a.label == ref.source_article), None)
        if art is not None and len(art.paras) <= 1:
            ref.source_para = None
    return g.refs


def make_addenda(rng: random.Random, reg: Regulation) -> list[Addendum]:
    spec = reg.spec
    K = spec.kind
    nouns = [n for _c, ns in spec.chapters for n in ns]
    live = [a for a in reg.articles if not a.deleted and a.arche not in ("general", "closing")]
    dates = [reg.enact] + list(reg.amendments)
    out: list[Addendum] = []
    for k, d in enumerate(dates):
        clauses: list[Clause] = []
        when = fmt_date_kr(d)
        if k == 0:
            clauses.append(Clause(1, "시행일", kf("이 {K:은} {when}부터 시행한다.", K=K, when=when)))
            if rng.random() < 0.5:
                clauses.append(Clause(2, "경과조치", kf("이 {K} 시행 전에 종전의 규정에 따라 행한 처분이나 절차는 이 {K}에 따라 행한 것으로 본다.", K=K)))
        else:
            if rng.random() < 0.8:
                text = kf("이 {K:은} {when}부터 시행한다.", K=K, when=when)
            else:
                text = kf("이 {K:은} 공포한 날부터 시행한다. 다만, 제{n}조의 개정규정은 {when}부터 시행한다.",
                          K=K, when=when, n=rng.choice(live).num)
            clauses.append(Clause(1, "시행일", text))
            r = rng.random()
            if r < 0.55:
                clauses.append(Clause(len(clauses) + 1, "경과조치", kf(
                    "이 {K} 시행 당시 종전의 규정에 따라 진행 중인 {N}에 관한 사항은 종전의 규정에 따른다.",
                    K=K, N=rng.choice(nouns))))
            if r > 0.35:
                clauses.append(Clause(len(clauses) + 1, "적용례", kf(
                    "제{n}조의 개정규정은 이 {K} 시행 후 최초로 신청하는 분부터 적용한다.",
                    K=K, n=rng.choice(live).num)))
        out.append(Addendum(d, clauses))
    return out


