_DIGIT_BATCHIM = {"0": True, "1": True, "2": False, "3": True, "4": False,
                  "5": False, "6": True, "7": True, "8": True, "9": False}
_TRAILING_SKIP = ")」』”’\"' ]>"


def _final_consonant(word: str) -> tuple[bool, bool]:
    """Return (has_final_consonant, final_is_rieul) for the last readable char."""
    for ch in reversed(word):
        if ch in _TRAILING_SKIP:
            continue
        if "가" <= ch <= "힣":
            tail = (ord(ch) - 0xAC00) % 28
            return tail != 0, tail == 8
        if ch in _DIGIT_BATCHIM:
            return _DIGIT_BATCHIM[ch], ch in "178"
        return False, False
    return False, False


_JOSA = {
    "은": ("은", "는"),
    "이": ("이", "가"),
    "을": ("을", "를"),
    "과": ("과", "와"),
    "이란": ("이란", "란"),
}


def josa(word: str, kind: str) -> str:
    """Append the correct particle (은/는, 이/가, 을/를, 과/와, 으로/로, 이란/란)."""
    has_final, rieul = _final_consonant(word)
    if kind == "로":
        return word + ("로" if (not has_final or rieul) else "으로")
    with_final, without_final = _JOSA[kind]
    return word + (with_final if has_final else without_final)


class _KFormatter(string.Formatter):
    """``str.format`` with Korean particle specs, e.g. ``{N:을}`` -> ``휴직을``."""

    def format_field(self, value: Any, format_spec: str) -> str:
        if format_spec in _JOSA or format_spec == "로":
            return josa(str(value), format_spec)
        return super().format_field(value, format_spec)


_KF = _KFormatter()


def kf(template: str, **values: Any) -> str:
    return _KF.vformat(template, (), values)


