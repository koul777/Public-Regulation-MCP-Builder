def _a_exception(g: Gen, N: str) -> tuple[str, list[Para]]:
    ref = g.internal_ref()
    if ref is None:
        return f"{N}의 특례", [P(g.f("{H:은} 업무상 불가피한 사유가 있는 경우에는 {C}의 심의를 거쳐 {N}에 관하여 별도의 기준을 정하여 적용할 수 있다.", N=N))]
